#!/usr/bin/env python3
"""The words Windows uses for an app's Settings item, in every language Wine translates.

An app written for Windows names its settings item in the language of Windows ("Paramètres" in French, "Einstellungen" in
German), which is not the Mac's word for it ("Réglages"). Wine's own translations carry Windows' words: the msgids
"Settings", "Options" and "Preferences" with their msgstrs. Writes runtime/Sources/W2SKit/WindowsWords.swift.

    tools/gen_windows_words.py <wine source tree>
"""
import glob, os, re, sys

src = sys.argv[1] if len(sys.argv) > 1 else os.environ.get("WINE_SRC", "")
ids = {"settings", "options", "preferences"}

def plain(text):
    text = text.replace('\\"', '"')
    text = re.sub(r"\(&.\)", "", text)          # East Asian mnemonic: 設定(&S)
    text = text.replace("&", "")
    text = re.sub(r"(\.\.\.|…)\s*$", "", text).strip()
    return text

words = set()
for path in sorted(glob.glob(os.path.join(src, "po", "*.po"))):
    data = open(path, encoding="utf-8", errors="ignore").read()
    for m in re.finditer(r'msgid "((?:[^"\\]|\\.)*)"\nmsgstr "((?:[^"\\]|\\.)*)"', data):
        if plain(m.group(1)).lower() in ids and m.group(2):
            words.add(plain(m.group(2)))
    words.update(w for w in ["Settings", "Options", "Preferences"])

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "runtime", "Sources", "W2SKit", "WindowsWords.swift")
with open(out, "w", encoding="utf-8") as f:
    f.write("// Generated by tools/gen_windows_words.py from Wine's translations: do not edit.\n")
    f.write("// What Windows calls an app's Settings item, in every language it is translated to.\n\n")
    f.write("enum WindowsWords {\n    static let settings: [String] = [\n")
    for w in sorted(words):
        f.write('        "%s",\n' % w.replace("\\", "\\\\").replace('"', '\\"'))
    f.write("    ]\n}\n")
print("%d words" % len(words))
